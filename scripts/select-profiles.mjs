#!/usr/bin/env node
// Chooses where the Worker gets the hosted profiles from and writes
// web/src/operator-profiles.generated.mjs, which is the only module the Worker
// imports them through.
//
//   node scripts/select-profiles.mjs                    the private module when it exists, else the stub
//   node scripts/select-profiles.mjs --stub             the stub, as in a checkout without the private module
//   node scripts/select-profiles.mjs --require-private  exit 1 unless the private module is used (the deploy gate)
//   node scripts/select-profiles.mjs --print            say which source the generated module names; write nothing
//
// BOUNTY_OPERATOR_PROFILES=stub (or =private) in the environment does the same
// as the flag, so a whole `npm test` can run on the stub.
//
// The private module is web/private/operator-profiles.mjs. That directory is
// git-ignored. The generated module is git-ignored too and holds no profile
// text: it re-exports from the chosen source.

import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const PRIVATE_MODULE = join(ROOT, 'web', 'private', 'operator-profiles.mjs');
export const STUB_MODULE = join(ROOT, 'web', 'src', 'operator-profiles.stub.mjs');
export const GENERATED_MODULE = join(ROOT, 'web', 'src', 'operator-profiles.generated.mjs');
const PUBLIC_PROFILES = join(ROOT, 'web', 'public', 'profiles.mjs');

const SOURCES = Object.freeze({
  private: { path: PRIVATE_MODULE, specifier: '../private/operator-profiles.mjs' },
  stub: { path: STUB_MODULE, specifier: './operator-profiles.stub.mjs' },
});

const SOURCE_LINE = /^export const PROFILE_SOURCE = '(private|stub)';$/m;

/** The text of the generated module for a source. It names the source and holds no profile text. */
export function generatedText(source) {
  return [
    '// GENERATED by scripts/select-profiles.mjs. Never edited by hand and never committed.',
    `export { OPERATOR_PROFILES } from '${SOURCES[source].specifier}';`,
    `export const PROFILE_SOURCE = '${source}';`,
    '',
  ].join('\n');
}

/** 'private' | 'stub' | null: what the generated module on disk names. */
export async function currentSource() {
  try {
    return SOURCE_LINE.exec(await readFile(GENERATED_MODULE, 'utf8'))?.[1] ?? null;
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

function headings(format) {
  return format.split('\n').filter((line) => line.startsWith('## ')).map((line) => line.slice(3).trim());
}

/**
 * Problems that make a profile module unusable: a hosted profile with no
 * method, an entry for an id that is not hosted, or sections that differ from
 * the titles the result view knows.
 */
export async function problemsIn(source) {
  const [{ PROFILES }, module] = await Promise.all([
    import(pathToFileURL(PUBLIC_PROFILES).href),
    import(`${pathToFileURL(SOURCES[source].path).href}?check=${Date.now()}`),
  ]);
  const entries = module.OPERATOR_PROFILES;
  if (!entries || typeof entries !== 'object') return ['it does not export OPERATOR_PROFILES'];

  const problems = [];
  const hosted = PROFILES.filter((profile) => profile.hosted);
  for (const profile of hosted) {
    const entry = Object.hasOwn(entries, profile.id) ? entries[profile.id] : null;
    if (!entry || typeof entry.instructions !== 'string' || !entry.instructions.trim()) {
      problems.push(`${profile.id}: no instructions`);
      continue;
    }
    if (typeof entry.extraFormat !== 'string' || headings(entry.extraFormat).join('|') !== profile.sections.join('|')) {
      problems.push(`${profile.id}: its output sections are not ${profile.sections.join(', ')}`);
    }
  }
  for (const id of Object.keys(entries)) {
    if (!hosted.some((profile) => profile.id === id)) problems.push(`${id}: not a hosted profile`);
  }
  return problems;
}

/**
 * Writes the generated module and returns the source it names.
 *
 * @param {'auto' | 'private' | 'stub'} [wanted]
 */
export async function selectProfiles(wanted = 'auto') {
  const source = wanted === 'auto' ? (existsSync(PRIVATE_MODULE) ? 'private' : 'stub') : wanted;
  if (!Object.hasOwn(SOURCES, source)) throw new Error(`Unknown profile source "${wanted}". Use private or stub.`);
  if (!existsSync(SOURCES[source].path)) {
    throw new Error(`The ${source} profile module is missing: ${SOURCES[source].path}`);
  }

  const problems = await problemsIn(source);
  if (problems.length) throw new Error(`The ${source} profile module cannot be used:\n${problems.map((problem) => `  ${problem}`).join('\n')}`);

  const text = generatedText(source);
  const current = await readFile(GENERATED_MODULE, 'utf8').catch(() => null);
  // Left alone when it already says the same, so a dev server does not reload on every test run.
  if (current !== text) await writeFile(GENERATED_MODULE, text);
  return source;
}

function wantedSource(argv, env) {
  if (argv.includes('--stub')) return 'stub';
  const fromEnv = env.BOUNTY_OPERATOR_PROFILES;
  if (fromEnv === 'stub' || fromEnv === 'private') return fromEnv;
  if (fromEnv) throw new Error('BOUNTY_OPERATOR_PROFILES must be stub or private.');
  return 'auto';
}

/**
 * Why a deploy must not go ahead with this source, or null when it may. Only
 * the private module holds the product; the stub is the community edition.
 *
 * @param {string} source  What selectProfiles returned.
 * @param {boolean} [privateExists]
 * @returns {string | null}
 */
export function deployRefusal(source, privateExists = existsSync(PRIVATE_MODULE)) {
  if (source === 'private') return null;
  const why = privateExists ? 'the stub was asked for (--stub or BOUNTY_OPERATOR_PROFILES=stub)' : `${PRIVATE_MODULE} does not exist`;
  return [
    'Refusing to deploy: the generated profile module came from the stub.',
    `  Cause: ${why}.`,
    '  The Worker would ship the community stub (web/src/operator-profiles.stub.mjs) as the paid profiles.',
    '  Restore the private module and select it, then run the deploy again.',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const argv = process.argv.slice(2);
  try {
    if (argv.includes('--print')) {
      console.log(`Hosted profiles: ${(await currentSource()) ?? 'not selected yet'}.`);
    } else {
      const source = await selectProfiles(wantedSource(argv, process.env));
      const refusal = argv.includes('--require-private') ? deployRefusal(source) : null;
      if (refusal) {
        console.error(refusal);
        process.exit(1);
      }
      if (!argv.includes('--quiet')) console.log(`Hosted profiles: ${source} module.`);
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
